import type { LoanStatus, MemberInput, MemberListQuery, MemberSortKey, MemberStatus } from "@slm/contracts";

/** A library patron. Not a user: no password, login or role (SLM-3 AC6). Members are deactivated, never deleted. */
export interface Member {
  id: string;
  memberNumber: string; // M-000123, generated by the database
  fullName: string;
  email: string; // stored lower-case; unique case-insensitively
  phone: string | null;
  status: MemberStatus;
  registeredAt: Date;
  version: number;
}

/** Read model: the member plus loan counts derived from the loans table (computed per query, never stored). */
export interface MemberView extends Member {
  activeLoans: number; // open loans, overdue included
  overdueLoans: number; // open loans past their due date
}

/** One loan of a member, with the names the screen shows. Same facts as LoanDto in contracts. */
export interface MemberLoanView {
  id: string;
  status: LoanStatus;
  book: { id: string; title: string; author: string };
  member: { id: string; memberNumber: string; fullName: string };
  processedBy: { id: string; name: string };
  returnedBy: { id: string; name: string } | null;
  borrowedAt: Date;
  dueAt: Date;
  returnedAt: Date | null;
}

export interface MemberListParams {
  q?: string;
  status?: MemberStatus;
  sort: { key: MemberSortKey; desc: boolean }[];
  page: number;
  size: number;
}

/** `ALL` and "no status" both mean no filter. */
export const statusFilter = (s: MemberListQuery["status"]): MemberStatus | undefined =>
  s === "ACTIVE" || s === "INACTIVE" ? s : undefined;

/** Outcome of a guarded write; the application turns non-ok results into domain errors. */
export type SaveResult = { kind: "ok"; member: MemberView } | { kind: "duplicate_email" };
export type UpdateResult = SaveResult | { kind: "not_found" } | { kind: "stale" };

export interface MemberRepository {
  findView(id: string): Promise<MemberView | null>;
  list(params: MemberListParams): Promise<{ items: MemberView[]; total: number }>;
  create(input: MemberInput): Promise<SaveResult>;
  /** One guarded statement: `WHERE id = ? AND version = ?`. */
  update(id: string, version: number, input: MemberInput & { status: MemberStatus }): Promise<UpdateResult>;
  /** Null when the member doesn't exist. Order: open overdue, open, then returned by returnedAt desc. */
  loansOf(memberId: string): Promise<MemberLoanView[] | null>;
}
